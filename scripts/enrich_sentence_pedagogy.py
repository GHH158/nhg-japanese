# Load knowledge-data.js
data_path = "data/knowledge-data.js"
with open(data_path, "r", encoding="utf-8") as f:
    content = f.read()

json_str = content.split("=", 1)[1].rsplit(";", 1)[0].strip()
kb = json.loads(json_str)

total_turns_enriched = 0
for sc in kb["scenes"]:
    s_id = sc["id"]
    if s_id in scene_pedagogy_map:
        pedagogy_list = scene_pedagogy_map[s_id]
        dialogue = sc.get("textbookText", {}).get("dialogue", [])
        if len(pedagogy_list) != len(dialogue):
            print(f"Warning: {s_id} dialogue length ({len(dialogue)}) != pedagogy length ({len(pedagogy_list)})")
        for idx, turn in enumerate(dialogue):
            if idx < len(pedagogy_list):
                turn["pedagogy"] = pedagogy_list[idx]
                total_turns_enriched += 1
        print(f"Enriched {s_id} with {len(dialogue)} detailed pedagogy items.")

# Write back to data/knowledge-data.js
output_js = f"// 日语学习平台核心知识库（Data-Driven Multi-Scene Knowledge Base）\nwindow.JAPANESE_KNOWLEDGE_BASE = {json.dumps(kb, ensure_ascii=False, indent=2)};\n"
with open(data_path, "w", encoding="utf-8") as f:
    f.write(output_js)

